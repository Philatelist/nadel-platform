package app.nadel.ledger.internal;

import app.nadel.ledger.internal.RecalculationPlanner.Line;
import app.nadel.ledger.internal.RecalculationPlanner.Plan;
import app.nadel.ledger.internal.RecalculationPlanner.QueueOutcome;
import app.nadel.ledger.internal.RecalculationPlanner.RunOutcome;
import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.time.YearMonth;
import java.util.ArrayList;
import java.util.Collection;
import java.util.HexFormat;
import java.util.List;
import java.util.Map;
import java.util.Objects;
import java.util.TreeMap;
import java.util.UUID;
import java.util.stream.Collectors;

/**
 * The digest of a recalculation (feature 012, technical considerations 2.2): a SHA-256 over the normalised cause, the
 * scope and the sorted lines ({@code identity|case|liveId|effective|expected|difference|targetMonth|servicePeriod}),
 * plus the run and queue outcomes. A booking with another digest than its preview is refused
 * ({@code PREVIEW_OUTDATED}). Pure.
 * <p>
 * It never contains an id generated by the change itself (a new tariff version, a new reading, the new charges): the
 * preview rolls the change back and the booking applies it again with new ids, so only identities, the ids of booked
 * charges and runs, amounts, months and dates go in. Every part is sorted, so the order of the input never matters.
 */
final class RecalculationDigest {

    private RecalculationDigest() {
    }

    /**
     * The cause, normalised by the caller: its type ({@code MANUAL}, {@code TARIFF_VERSION_UPDATE}, …) and its values
     * as text (for example the tariff, the old and new terms of a version, the meter and the old and new date and
     * value of a reading), never the id of something the change creates.
     */
    record Cause(String type, Map<String, String> values) {

        Cause {
            Objects.requireNonNull(type, "type");
            values = new TreeMap<>(values);
        }

        static Cause manual() {
            return new Cause("MANUAL", Map.of());
        }
    }

    /** The scope: months, charge types and plots (any order). */
    record Scope(Collection<YearMonth> months, Collection<UUID> chargeTypeIds, Collection<UUID> plotIds) {

        Scope {
            months = List.copyOf(months);
            chargeTypeIds = List.copyOf(chargeTypeIds);
            plotIds = List.copyOf(plotIds);
        }
    }

    /** The digest, as 64 hex digits. */
    static String of(Cause cause, Scope scope, Plan plan) {
        List<String> text = new ArrayList<>();
        text.add("C|" + cause.type());
        cause.values().forEach((key, value) -> text.add("C|" + key + "=" + value));
        text.add("S|M|" + sorted(scope.months()));
        text.add("S|T|" + sorted(scope.chargeTypeIds()));
        text.add("S|P|" + sorted(scope.plotIds()));
        List<String> rest = new ArrayList<>();
        for (Line line : plan.lines()) {
            rest.add("L|" + line.identity() + "|" + line.action() + "|"
                    + (line.original() == null ? "-" : line.original().id()) + "|" + line.effective() + "|"
                    + line.expected() + "|" + line.difference() + "|" + line.bookedIn() + "|" + line.serviceFrom()
                    + ".." + line.serviceTo());
        }
        for (RunOutcome run : plan.runs()) {
            rest.add("R|" + run.runId() + "|" + run.action());
        }
        for (QueueOutcome item : plan.queue()) {
            // the identity, not the item key: the key of an interval item holds a reading's id
            rest.add("Q|" + (item.identity() == null ? item.itemKey() : item.identity()) + "|" + item.status() + "|"
                    + item.reason());
        }
        rest.sort(null);
        text.addAll(rest);
        try {
            return HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256")
                    .digest(String.join("\n", text).getBytes(StandardCharsets.UTF_8)));
        } catch (NoSuchAlgorithmException e) {
            throw new IllegalStateException("SHA-256 is always available", e);
        }
    }

    private static String sorted(Collection<?> values) {
        return values.stream().map(Object::toString).sorted().collect(Collectors.joining(","));
    }
}
