package app.nadel.plots.internal;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import java.math.BigDecimal;
import java.time.Instant;
import java.util.UUID;
import org.locationtech.jts.geom.Polygon;

@Entity
@Table(name = "plot")
class Plot {

    @Id
    private UUID id;

    @Column(name = "tenant_id", nullable = false, updatable = false)
    private UUID tenantId;

    @Column(nullable = false)
    private String number;

    private String street;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false)
    private PlotKind kind;

    @Column(name = "area_m2", nullable = false)
    private BigDecimal areaM2;

    @Column(name = "cadastral_number")
    private String cadastralNumber;

    @Column(columnDefinition = "geometry(Polygon,4326)")
    private Polygon boundary;

    @Column(name = "has_building", nullable = false)
    private boolean hasBuilding;

    private String notes;

    @Column(name = "archived_at")
    private Instant archivedAt;

    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    @Column(name = "updated_at", nullable = false)
    private Instant updatedAt;

    // plot.number_sort_key is generated by the database and deliberately not mapped

    protected Plot() {
    }

    /** A new active plot of a cooperative. */
    static Plot create(UUID tenantId, PlotData data, Instant now) {
        return create(UUID.randomUUID(), tenantId, data, now);
    }

    /** A new active plot with a given id: the Excel import derives the id from the import, so a re-plan agrees. */
    static Plot create(UUID id, UUID tenantId, PlotData data, Instant now) {
        Plot plot = new Plot();
        plot.id = id;
        plot.tenantId = tenantId;
        plot.createdAt = now;
        plot.apply(data);
        plot.updatedAt = now;
        return plot;
    }

    /**
     * Overwrites every editable field with {@code data}. Does not stamp {@code updatedAt}: the caller calls
     * {@link #touch} only when the audited fields really changed.
     */
    void apply(PlotData data) {
        number = data.number();
        street = data.street();
        kind = data.kind();
        areaM2 = data.areaM2();
        cadastralNumber = data.cadastralNumber();
        hasBuilding = data.hasBuilding();
        notes = data.notes();
    }

    void touch(Instant now) {
        updatedAt = now;
    }

    void archive(Instant now) {
        archivedAt = now;
        updatedAt = now;
    }

    void restore(Instant now) {
        archivedAt = null;
        updatedAt = now;
    }

    UUID getId() {
        return id;
    }

    UUID getTenantId() {
        return tenantId;
    }

    String getNumber() {
        return number;
    }

    String getStreet() {
        return street;
    }

    PlotKind getKind() {
        return kind;
    }

    BigDecimal getAreaM2() {
        return areaM2;
    }

    String getCadastralNumber() {
        return cadastralNumber;
    }

    Polygon getBoundary() {
        return boundary;
    }

    boolean hasBuilding() {
        return hasBuilding;
    }

    String getNotes() {
        return notes;
    }

    Instant getArchivedAt() {
        return archivedAt;
    }

    Instant getCreatedAt() {
        return createdAt;
    }

    Instant getUpdatedAt() {
        return updatedAt;
    }
}
